"""Import the pinned upstream SVG sprite and exported icon aliases, without executing package code."""
from pathlib import Path
import base64
import hashlib
import json
import re
import sys
import tarfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
VERSION = '0.468.0'
INTEGRITY = 'JvpWui2umxRyEVMoETfMzb+qKqibV/sdoqJbKmW1JLdkuhXluJKoO6NqCbvCK/vAbUuH5bTEFD4T6uECsrNcnA=='
archive_path = Path(sys.argv[1])
assert base64.b64encode(hashlib.sha512(archive_path.read_bytes()).digest()).decode() == INTEGRITY
with tarfile.open(archive_path, 'r:gz') as archive:
    inputs = {name: archive.extractfile('package/' + name).read() for name in ['sprite.svg', 'LICENSE', 'dist/esm/lucide-static.js']}

sprite = ET.fromstring(inputs['sprite.svg'])
ids = [node.attrib['id'] for node in sprite.findall('.//{http://www.w3.org/2000/svg}symbol')]
assert len(ids) == 1544 and len(set(ids)) == len(ids)
allowed = {'svg', 'defs', 'symbol', 'path', 'circle', 'ellipse', 'line', 'polyline', 'polygon', 'rect', 'title'}
for node in sprite.iter():
    assert node.tag.split('}')[-1] in allowed
    assert all(not key.lower().startswith('on') and key not in ['href', 'style'] for key in node.attrib)

def kebab(value):
    value = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1-\2', value)
    value = re.sub(r'([a-z0-9])([A-Z])', r'\1-\2', value)
    value = re.sub(r'([a-z])([0-9])', r'\1-\2', value)
    return value.lower()

aliases = {}
for exports, canonical in re.findall(r"export \{ ([^}]+) \} from './icons/([^']+)\.js';", inputs['dist/esm/lucide-static.js'].decode()):
    assert canonical in ids
    for exported in re.findall(r'default as ([A-Za-z0-9]+)', exports):
        name = kebab(exported)
        if name != canonical and name not in ids:
            assert name not in aliases or aliases[name] == canonical
            aliases[name] = canonical

outputs = {
    'src/RonSijm.Slopsidian/wwwroot/lucide-icons.svg': inputs['sprite.svg'],
    'src/RonSijm.Slopsidian/wwwroot/lucide-icons-LICENSE.txt': inputs['LICENSE'],
    'client/lucide-icon-aliases.ts': ('// Generated by tools/import-lucide-icons.py from lucide-static ' + VERSION + '.\n'
        + 'export const lucideIconAliases: Readonly<Record<string, string>> = ' + json.dumps(dict(sorted(aliases.items())), indent=2) + ';\n').encode(),
}
record = {
    'package': 'lucide-static', 'version': VERSION,
    'url': 'https://registry.npmjs.org/lucide-static/-/lucide-static-' + VERSION + '.tgz',
    'integrity': 'sha512-' + INTEGRITY, 'license': 'ISC', 'symbols': len(ids), 'aliases': len(aliases),
    'upstreamSha256': {name: hashlib.sha256(data).hexdigest() for name, data in inputs.items()},
    'sha256': {name: hashlib.sha256(data).hexdigest() for name, data in outputs.items()},
}
for name, data in outputs.items():
    (ROOT / name).write_bytes(data)
directory = ROOT / 'vendor/lucide-static'
directory.mkdir(parents=True, exist_ok=True)
(directory / 'provenance.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
print(json.dumps({'symbols': len(ids), 'aliases': len(aliases), 'outputs': list(outputs)}))
